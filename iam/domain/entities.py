"""Domain entities for the IAM bounded context.

This module defines the aggregate root used by the edge service to represent a
registered QualiTrack IoT device. Entities carry identity across their lifetime
and encapsulate state that is only modified by services enforcing domain
invariants.
"""
from datetime import datetime

from iam.domain.enums import DeviceType
from iam.domain.enums import DeviceStatus

class Device:
    """Aggregate root representing a registered QualiTrack IoT device.

    A ``Device`` is an ESP32 node (Environment Monitor or Container Monitor)
    identified by its MAC-address ``device_id`` and authenticated through its
    paired ``device_token``. Device registration and lookup are managed by the
    :class:`~iam.infrastructure.repositories.DeviceRepository`.

    Attributes:
        device_id (str): Device MAC address used as a public identifier.
        device_token (str): Secret token generated by the cloud and used to
            authenticate HTTP requests generated by the device.
        device_type (str): Type of node (environment or container monitor).
        status (str): Device lifecycle status.
        created_at (datetime): UTC timestamp recording when the device was
            first registered in the local edge database.
    """

    def __init__(
        self,
        device_id: str,
        device_token: str,
        created_at: datetime,
        status: str = DeviceStatus.REGISTERED.name,
        device_type: str = DeviceType.ENVIRONMENT_MONITOR.name
    ):
        """Initialize a Device aggregate root.

        Args:
            device_id (str): MAC-address QualiTrack IoT device identifier.
            device_token (str): Secret token paired with the device.
            status (str): Device lifecycle status.
            created_at (datetime): UTC timestamp of device registration.
            device_type (str): Type of node.
        """
        self.device_id = device_id
        self.device_token = device_token
        self.created_at = created_at
        self.status: str = status
        self.device_type: str = device_type


